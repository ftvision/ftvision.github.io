/**
 * Determine decade from year
 */
export function getDecade(year: number): Decade {
  if (year < 1960) return '1950s';
  if (year < 1970) return '1960s';
  if (year < 1980) return '1970s';
  if (year < 1990) return '1980s';
  if (year < 2000) return '1990s';
  return '2000s';
}

/**
 * Get line configuration by topic
 */
export function getLineByTopic(topic: string): SubwayLine | undefined {
  return SUBWAY_LINES.find(line => line.id === topic);
}

