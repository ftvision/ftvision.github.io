/**
 * Get papers grouped by topic
 */
export function getPapersByTopic(): Map<string, VisionPaper[]> {
  const grouped = new Map<string, VisionPaper[]>();
  for (const paper of VISION_100_PAPERS) {
    if (!grouped.has(paper.topic)) {
      grouped.set(paper.topic, []);
    }
    grouped.get(paper.topic)!.push(paper);
  }
  return grouped;
}

/**
 * Get papers grouped by decade
 */
export function getPapersByDecade(): Map<Decade, VisionPaper[]> {
  const grouped = new Map<Decade, VisionPaper[]>();
  for (const paper of VISION_100_PAPERS) {
    if (!grouped.has(paper.decade)) {
      grouped.set(paper.decade, []);
    }
    grouped.get(paper.decade)!.push(paper);
  }
  return grouped;
}
